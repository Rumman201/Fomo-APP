package com.example.fomo;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertNotNull;
import static org.junit.Assert.assertTrue;

import androidx.annotation.NonNull;
import androidx.arch.core.executor.testing.InstantTaskExecutorRule;
import com.example.fomo.data.repository.InMemoryWeatherRepository;
import com.example.fomo.domain.model.City;
import com.example.fomo.domain.model.WeatherForecast;
import com.example.fomo.domain.repository.WeatherRepository;
import com.example.fomo.ui.viewmodel.WeatherUiState;
import com.example.fomo.ui.viewmodel.WeatherViewModel;
import org.junit.Rule;
import org.junit.Test;

/**
 * Unit tests for WeatherViewModel state transitions, multi-city selection, and repository interaction.
 */
public class WeatherViewModelTest {

    @Rule
    public InstantTaskExecutorRule instantTaskExecutorRule = new InstantTaskExecutorRule();

    @Test
    public void testViewModelEmitsSuccessStateOnLoad() {
        WeatherRepository testRepository = new InMemoryWeatherRepository(Runnable::run, Runnable::run);
        WeatherViewModel viewModel = new WeatherViewModel(testRepository);

        WeatherUiState state = viewModel.getUiState().getValue();
        assertNotNull(state);
        assertTrue(state.isSuccess());
        assertNotNull(state.getData());
        assertEquals("Mostly Cloudy", state.getData().getCurrentWeather().getCondition());
        assertEquals(5, state.getData().getHourlyForecasts().size());
        assertNotNull("AI advisory should be generated by default", state.getAiAdvisory());
        assertNotNull("Selected city should be initialized", state.getSelectedCity());
    }

    @Test
    public void testViewModelEmitsErrorStateOnRepositoryFailure() {
        WeatherRepository failingRepository = new WeatherRepository() {
            @NonNull
            @Override
            public WeatherForecast getSynchronousForecast() {
                throw new RuntimeException("Simulated network outage");
            }

            @Override
            public void getForecastAsync(@NonNull Callback<WeatherForecast> callback) {
                callback.onError(new RuntimeException("Simulated network outage"));
            }

            @Override
            public void getForecastForLocationAsync(double latitude, double longitude, @NonNull Callback<WeatherForecast> callback) {
                callback.onError(new RuntimeException("Simulated network outage"));
            }
        };

        WeatherViewModel viewModel = new WeatherViewModel(failingRepository);

        WeatherUiState state = viewModel.getUiState().getValue();
        assertNotNull(state);
        assertTrue(state.isError());
        assertEquals("Simulated network outage", state.getErrorMessage());
    }

    @Test
    public void testCitySelectionUpdatesActiveLocation() {
        WeatherRepository testRepository = new InMemoryWeatherRepository(Runnable::run, Runnable::run);
        WeatherViewModel viewModel = new WeatherViewModel(testRepository);

        City tokyo = new City(2, "Tokyo", "Japan", null, 35.6762, 139.6503, false, 0L);
        viewModel.selectCity(tokyo);

        assertEquals("Tokyo", viewModel.getCurrentCity().getName());
        WeatherUiState state = viewModel.getUiState().getValue();
        assertNotNull(state);
        assertEquals("Tokyo", state.getSelectedCity().getName());
    }

    @Test
    public void testSyncLoadStateTransition() {
        WeatherRepository testRepository = new InMemoryWeatherRepository(Runnable::run, Runnable::run);
        WeatherViewModel viewModel = new WeatherViewModel(testRepository);

        viewModel.loadWeatherSync();

        WeatherUiState state = viewModel.getUiState().getValue();
        assertNotNull(state);
        assertTrue(state.isSuccess());
    }
}
